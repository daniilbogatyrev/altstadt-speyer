#!/usr/bin/env bash
# Converts the original photos in images/<Ordner>/ into optimised WebP files in img/<kategorie>/
# and writes js/photos.js (order = order listed below). Re-run after adding/reordering photos.
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=images
rm -rf img && mkdir -p img

declare -A DIR=( [wohnen]="Wohnzimmer+Küche" [schlafen]="Schlafzimmer" [bad]="Bad" [hof]="Außenbereich" [anreise]="Location" )
declare -A ORDER=(
  [wohnen]="806546288 806546656 806546448 806548248 806546203 806548344 806548494 806548403 806546535 806604853 806546815 806604163 806604721"
  [schlafen]="806547931 806548085 806529395 807139359 806547432 806548735 807038348 806567033"
  [bad]="806545901 806547775 806548839"
  [hof]="642148835 806604539 807072411 806548561 806604987 806605219 642149435 807084906 806604391 806566439 806549482 806603852 806604593 806548994"
  [anreise]="711046378 806577127 806549954 806565565 607213528"
)

{
  echo "/* generated by tools/build-images.sh */"
  echo "window.PHOTOS = {"
  for cat in wohnen schlafen bad hof anreise; do
    mkdir -p "img/$cat"
    echo "  $cat: ["
    i=0
    for id in ${ORDER[$cat]}; do
      i=$((i+1)); n=$(printf '%02d' $i)
      f="$SRC/${DIR[$cat]}/$id.jpg"
      magick "$f" -strip -resize '1600x1600>' -quality 74 -define webp:method=6 "img/$cat/$n.webp"
      magick "$f" -strip -resize "560x560>" -quality 68 -define webp:method=6 "img/$cat/$n-s.webp"
      wh=$(identify -format "%w %h" "img/$cat/$n.webp"); w=${wh% *}; h=${wh#* }
      echo "    { src: \"img/$cat/$n.webp\", thumb: \"img/$cat/$n-s.webp\", w: $w, h: $h },"
    done
    echo "  ],"
  done
  echo "};"
} > js/photos.js

# Favicon from the Speyer coat of arms (source in favicon/)
COA=$(ls favicon/*.webp | head -1)
magick "$COA" -background none -gravity center -resize 512x512 -extent 512x512 /tmp/coa-512.png
magick /tmp/coa-512.png -resize 32x32 favicon-32.png
magick /tmp/coa-512.png -resize 180x180 -background white -flatten apple-touch-icon.png
magick /tmp/coa-512.png -define icon:auto-resize=48,32,16 favicon.ico
rm -f /tmp/coa-512.png
echo "done: $(find img -name '*.webp' | wc -l) files, $(du -sh img | cut -f1)"
